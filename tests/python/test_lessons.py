class LessonBase(core.Base):
    def setUp(self):
        core.Base.setUp(self)
        os.makedirs(os.path.join(self.root, "myapp"))

    def add(self, *extra, scope="global", repo=None, **kw):
        argv = list(ADD) + ["--scope", scope] + (["--repo", repo] if repo else []) + list(extra)
        return self.ok(*argv, **kw)

    def gdir(self):
        return os.path.join(self.root, "lessons")

    def rdir(self):
        return os.path.join(self.root, "myapp", "lessons")

    def text(self, *parts):
        return self.read(*parts).decode("utf-8")

    def write(self, path, text):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)

    def check(self, code=0):
        rc, out, err = self.run_orch("lessons", "check")
        self.assertEqual(rc, code, out + err)
        return out


class TestAdd(LessonBase):
    def test_round_trip_global(self):
        out, _ = self.add()
        name = TODAY + "-check-the-export-round-trip"
        self.assertEqual(out.strip(), "global/" + name)
        text = self.text(self.gdir(), name + ".md")
        self.assertEqual(text.splitlines()[0], "# Check the export round trip")
        self.assertEqual(text.splitlines()[1:], [
            "- status: open", "- role: code-reviewer", "- scope: global",
            "- summary: Verify public safety with the export dry run, never a hand-written grep.",
            "- quote: none (observed: review round 2)", "- review-by: 2027-02-01", "- exempt: no",
            "- lesson: Run the export dry run before each review round and quote its refusal count."])
        index = self.text(self.root, "LESSONS.md")
        self.assertIn("Generated by `orch lessons index`", index.splitlines()[0])
        self.assertIn("Edit the files in lessons/", index.splitlines()[0])
        self.assertEqual(index.splitlines()[1], "- %s · code-reviewer · Verify public safety with the export dry run, "
                                                 "never a hand-written grep. → lessons/%s.md" % (TODAY, name))
        self.assertEqual(len(index.splitlines()), 2)
        self.assertIn("clean", self.check())

    def test_round_trip_project_with_optional_fields(self):
        out, _ = self.add("--task", "orch-init (orch-skill)", "--what-happened", "a grep said 0 hits",
                          "--actually-true", "only the round trip applies it", "--exempt", "it guards public safety",
                          "--quote", '"never trust a hand-written grep"', scope="project", repo="myapp")
        self.assertTrue(out.startswith("myapp/" + TODAY))
        text = self.text(self.rdir(), TODAY + "-check-the-export-round-trip.md")
        self.assertIn("- scope: project\n- task: orch-init (orch-skill)\n- summary:", text)
        self.assertIn("- exempt: yes — it guards public safety\n- what happened: a grep said 0 hits\n"
                      "- what was actually true: only the round trip applies it\n- lesson:", text)
        self.assertIn('- quote: "never trust a hand-written grep"', text)
        self.assertTrue(os.path.exists(os.path.join(self.root, "myapp", "LESSONS.md")))
        self.assertFalse(os.path.exists(os.path.join(self.root, "LESSONS.md")))
        self.assertIn("clean", self.check())

    def test_project_repo_from_the_task(self):
        self.init()
        out, _ = self.ok(*(ADD + ("--scope", "project", "-t", "myapp/add-login")))
        self.assertTrue(out.startswith("myapp/"))

    def test_index_is_oldest_first_and_names_the_pointers(self):
        for day, title in (("2026-03-05", "second"), ("2026-03-01", "first")):
            self.add("--title", title, now=day + "T10:00Z")
        lines = self.text(self.root, "LESSONS.md").splitlines()[1:]
        self.assertEqual([l.split(" · ")[0] for l in lines], ["- 2026-03-01", "- 2026-03-05"])
        self.assertTrue(lines[0].endswith("→ lessons/2026-03-01-first.md"))
        self.ok("lessons", "promote", "global/2026-03-01-first", "--to", "SKILL.md step 4")
        last = self.text(self.root, "LESSONS.md").splitlines()[-1]
        self.assertIn("lessons/PROMOTED.md", last)
        self.assertIn("lessons/archive/", last)
        self.assertIn("clean", self.check())

    def test_refusals_write_nothing(self):
        self.add()
        before = core.tree_hash(self.root)
        cases = [
            (dict(scope="task"), "belongs in that task's plan"),
            (dict(scope="team"), "--scope must be"),
            (dict(extra=("--summary", "x" * 201)), "over 200"),
            (dict(extra=("--summary", "two\nlines")), "one line"),
            (dict(extra=("--quote", "")), "--quote is required"),
            (dict(extra=("--review-by", "2027-13-40")), "YYYY-MM-DD"),
            (dict(extra=("--review-by", "soon")), "YYYY-MM-DD"),
            (dict(extra=("--quote", "plain words")), "quote must be"),
            (dict(extra=("--title", "!!!")), "empty file name"),
            (dict(extra=("--role", "!!!")), "must name a role"),
            (dict(extra=()), "already exists"),
            (dict(scope="project", repo="nope"), "no repo folder"),
            (dict(scope="project"), "needs --repo"),
        ]
        for kw, want in cases:
            scope = kw.get("scope", "global")
            argv = list(ADD) + ["--scope", scope] + (["--repo", kw["repo"]] if kw.get("repo") else []) + list(kw.get("extra", ()))
            rc, out, err = self.run_orch(*argv)
            self.assertEqual(rc, 1, (kw, out, err))
            self.assertIn(want, err, kw)
            self.assertEqual(core.tree_hash(self.root), before, kw)

    def test_a_dev_copy_without_orch_dir_refuses(self):
        # require_write_allowed: covered for the whole CLI in test_core; here the verb is wired to it
        import inspect
        for fn in (ls.cmd_add, ls.cmd_promote, ls.cmd_index):
            self.assertIn("require_write_allowed", inspect.getsource(fn))


class TestCheck(LessonBase):
    def lesson(self, scope_dir, name, **over):
        fields = dict([("status", "open"), ("role", "implementer"), ("scope", "global" if scope_dir.startswith(self.gdir()) else "project"),
                       ("summary", "Do the thing."), ("quote", "none (observed: test)"), ("review-by", "2027-02-01"),
                       ("exempt", "no"), ("lesson", "Do the thing, then check it.")])
        fields.update(over)
        text = "# A lesson\n" + "".join("- %s: %s\n" % (k, v) for k, v in fields.items() if v is not None)
        self.write(os.path.join(scope_dir, name + ".md"), text)

    def clean_global(self):
        self.lesson(self.gdir(), "2026-03-01-a-lesson")
        self.ok("lessons", "index")

    def test_clean(self):
        self.clean_global()
        out = self.check()
        self.assertIn("1 file in 1 scope, clean", out)

    def test_no_lessons_is_a_skip(self):
        self.assertEqual(self.check().strip(), "lessons: no lesson files (skip)")

    def test_a_hand_edited_index_fails(self):
        self.clean_global()
        with open(os.path.join(self.root, "LESSONS.md"), "a", encoding="utf-8") as fh:
            fh.write("- 2026-03-09 · planner · sneaked in → lessons/none.md\n")
        out = self.check(1)
        self.assertIn("global: LESSONS.md differs from the files", out)
        self.ok("lessons", "index")
        self.check()

    def test_a_missing_index_fails(self):
        self.clean_global()
        os.unlink(os.path.join(self.root, "LESSONS.md"))
        self.assertIn("LESSONS.md is missing", self.check(1))

    def test_each_defect_is_a_line(self):
        cases = [
            (dict(summary="x" * 201), "summary is 201 characters, over 200"),
            (dict(summary=None), "missing field 'summary'"),
            (dict(quote=None), "missing field 'quote'"),
            (dict(quote="plain"), "quote must be"),
            (dict(quote='"'), "quote must be"),
            (dict(status="done"), "status must be open, promoted or archived"),
            (dict(status="promoted"), "status promoted but the file is not in archive/"),
            (dict(scope="project"), "scope project but the file sits in a global lessons folder"),
            (dict(scope="team"), "scope must be project or global"),
            (dict(**{"review-by": "next week"}), "review-by must be YYYY-MM-DD"),
            (dict(exempt="maybe"), "exempt must be"),
            (dict(exempt="yes"), "exempt must be"),
            (dict(lesson=None), "missing field 'lesson'"),
            (dict(role=None), "missing field 'role'"),
        ]
        for over, want in cases:
            self.lesson(self.gdir(), "2026-03-01-a-lesson", **over)
            self.ok("lessons", "index")
            out = self.check(1)
            self.assertIn(want, out, (over, out))
            self.assertIn("global/2026-03-01-a-lesson.md:", out)

    def test_scope_placement_in_a_repo_folder(self):
        self.lesson(self.rdir(), "2026-03-01-a-lesson", scope="global")
        self.ok("lessons", "index")
        self.assertIn("myapp/2026-03-01-a-lesson.md: scope global but the file sits in a project lessons folder", self.check(1))

    def test_bad_names_and_titles(self):
        self.lesson(self.gdir(), "no-date-here")
        self.ok("lessons", "index")
        self.assertIn("file name must be", self.check(1))
        os.unlink(os.path.join(self.gdir(), "no-date-here.md"))
        self.lesson(self.gdir(), "2026-03-01-" + "a" * 61)
        self.ok("lessons", "index")
        self.assertIn("file name must be", self.check(1))
        os.unlink(os.path.join(self.gdir(), "2026-03-01-" + "a" * 61 + ".md"))
        self.write(os.path.join(self.gdir(), "2026-03-01-no-title.md"), "- status: open\n- role: planner\n")
        self.ok("lessons", "index")
        out = self.check(1)
        self.assertIn("no `# title` line", out)

    def test_duplicate_field(self):
        self.write(os.path.join(self.gdir(), "2026-03-01-dup.md"),
                   "# t\n- status: open\n- status: open\n- role: planner\n- scope: global\n- summary: s\n- quote: none (observed: x)\n"
                   "- review-by: 2027-01-01\n- exempt: no\n- lesson: l\n")
        self.ok("lessons", "index")
        self.assertIn("field 'status' twice", self.check(1))

    def test_other_fields_and_continuation_lines_are_kept(self):
        self.write(os.path.join(self.gdir(), "2026-03-01-extra.md"),
                   "# t\n- status: open\n- role: planner\n- scope: global\n- summary: s\n- quote: none (observed: x)\n"
                   "- review-by: 2027-01-01\n- exempt: no\n- mood: calm\n- lesson: first part\n  second part\n")
        l = ls.parse_lesson("x", self.text(self.gdir(), "2026-03-01-extra.md"))
        self.assertEqual(l.get("mood"), "calm")
        self.assertEqual(l.get("lesson"), "first part\nsecond part")
        self.assertEqual([k for k, _ in l.fields][-2:], ["mood", "lesson"])
        self.ok("lessons", "index")
        self.check()

    def test_archive_files_are_validated_and_not_indexed(self):
        self.clean_global()
        self.lesson(os.path.join(self.gdir(), "archive"), "2026-02-01-old", status="archived")
        self.ok("lessons", "index")
        self.assertNotIn("2026-02-01", self.text(self.root, "LESSONS.md").split("Promoted and archived")[0])
        self.check()
        self.lesson(os.path.join(self.gdir(), "archive"), "2026-02-01-old", status="open")
        self.assertIn("status open but the file is in archive/", self.check(1))

    def test_check_takes_a_root(self):
        other = os.path.join(self.tmp, "elsewhere")
        self.write(os.path.join(other, "lessons", "2026-03-01-x.md"), "# t\n- status: open\n")
        rc, out, _ = self.run_orch("lessons", "check", "--root", other)
        self.assertEqual(rc, 1)
        self.assertIn("missing field", out)
        self.check()      # the real root is unaffected

    def test_check_is_read_only(self):
        self.clean_global()
        before = core.tree_hash(self.root)
        self.check()
        self.assertEqual(core.tree_hash(self.root), before)


class TestPromote(LessonBase):
    def test_moves_to_archive_and_appends_a_row(self):
        self.add()
        name = TODAY + "-check-the-export-round-trip"
        out, _ = self.ok("lessons", "promote", "global/" + name, "--to", "SKILL.md step 5 | rule")
        self.assertIn("promoted global/" + name, out)
        self.assertFalse(os.path.exists(os.path.join(self.gdir(), name + ".md")))
        archived = self.text(self.gdir(), "archive", name + ".md")
        self.assertIn("- status: promoted\n", archived)
        self.assertNotIn("- status: open", archived)
        table = self.text(self.gdir(), "PROMOTED.md").splitlines()
        self.assertEqual(table[2:4], ["| date | lesson | promoted to |", "|---|---|---|"])
        self.assertEqual(table[4], "| %s | Verify public safety with the export dry run, never a hand-written grep. (%s) | SKILL.md step 5 / rule |"
                         % (TODAY, name))
        self.assertEqual(len(self.text(self.root, "LESSONS.md").splitlines()), 2)       # notice + pointer line, no lesson line
        self.assertIn("clean", self.check())
        self.add("--title", "Second one")
        self.ok("lessons", "promote", "global/%s-second-one" % TODAY, "--to", "TIERS.md")
        self.assertEqual(len(self.text(self.gdir(), "PROMOTED.md").splitlines()), 6)

    def test_refusals(self):
        self.add()
        name = TODAY + "-check-the-export-round-trip"
        before = core.tree_hash(self.root)
        for argv, want in ((("lessons", "promote", "global/" + name), "--to is required"),
                           (("lessons", "promote", "--to", "x"), "takes a lesson id"),
                           (("lessons", "promote", "nonsense", "--to", "x"), "lesson id is"),
                           (("lessons", "promote", "global/2026-01-01-none", "--to", "x"), "no open lesson"),
                           (("lessons", "promote", "../x/" + name, "--to", "x"), "lesson id is"),
                           (("lessons", "promote", ".hidden/" + name, "--to", "x"), "bad lesson id"),
                           (("lessons", "promote", "global/../" + name, "--to", "x"), "lesson id is")):
            rc, out, err = self.run_orch(*argv)
            self.assertEqual(rc, 1, argv)
            self.assertIn(want, err, argv)
        self.assertEqual(core.tree_hash(self.root), before)
        self.ok("lessons", "promote", "global/" + name, "--to", "x")
        self.refuse(1, "lessons", "promote", "global/" + name, "--to", "x")     # no longer open (it is archived)


class TestIndexCommand(LessonBase):
    def test_all_scopes_or_one(self):
        self.add()
        self.add("--title", "In repo", scope="project", repo="myapp")
        for p in (os.path.join(self.root, "LESSONS.md"), os.path.join(self.root, "myapp", "LESSONS.md")):
            os.unlink(p)
        out, _ = self.ok("lessons", "index", "--scope", "global")
        self.assertEqual(out.strip(), "global: LESSONS.md written")
        self.assertFalse(os.path.exists(os.path.join(self.root, "myapp", "LESSONS.md")))
        out, _ = self.ok("lessons", "index")
        self.assertEqual(sorted(out.splitlines()), ["global: LESSONS.md unchanged", "myapp: LESSONS.md written"])
        out, _ = self.ok("lessons", "index", "--repo", "myapp")
        self.assertEqual(out.strip(), "myapp: LESSONS.md unchanged")

    def test_nothing_to_index(self):
        out, _ = self.ok("lessons", "index")
        self.assertIn("nothing to index", out)

    def test_a_positional_where_none_is_taken(self):
        self.refuse(1, "lessons", "check", "oops")


