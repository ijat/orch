class TestCheck(LessonBase):
    def lesson(self, scope_dir, name, **over):
        fields = dict([("status", "open"), ("role", "implementer"), ("scope", "global" if scope_dir.startswith(self.gdir()) else "project"),
                       ("summary", "Do the thing."), ("quote", "none (observed: test)"), ("review-by", "2027-02-01"),
                       ("exempt", "no"), ("lesson", "Do the thing, then check it.")])
        fields.update(over)
        text = "# A lesson\n" + "".join("- %s: %s\n" % (k, v) for k, v in fields.items() if v is not None)
        self.write(os.path.join(scope_dir, name + ".md"), text)

    def clean_global(self):
        self.lesson(self.gdir(), "2026-03-01-a-lesson")
        self.ok("lessons", "index")

    def test_clean(self):
        self.clean_global()
        out = self.check()
        self.assertIn("1 file in 1 scope, clean", out)

    def test_no_lessons_is_a_skip(self):
        self.assertEqual(self.check().strip(), "lessons: no lesson files (skip)")

    def test_a_hand_edited_index_fails(self):
        self.clean_global()
        with open(os.path.join(self.root, "LESSONS.md"), "a", encoding="utf-8") as fh:
            fh.write("- 2026-03-09 · planner · sneaked in → lessons/none.md\n")
        out = self.check(1)
        self.assertIn("global: LESSONS.md differs from the files", out)
        self.ok("lessons", "index")
        self.check()

    def test_a_missing_index_fails(self):
        self.clean_global()
        os.unlink(os.path.join(self.root, "LESSONS.md"))
        self.assertIn("LESSONS.md is missing", self.check(1))

    def test_each_defect_is_a_line(self):
        cases = [
            (dict(summary="x" * 201), "summary is 201 characters, over 200"),
            (dict(summary=None), "missing field 'summary'"),
            (dict(quote=None), "missing field 'quote'"),
            (dict(quote="plain"), "quote must be"),
            (dict(quote='"'), "quote must be"),
            (dict(status="done"), "status must be open, promoted or archived"),
            (dict(status="promoted"), "status promoted but the file is not in archive/"),
            (dict(scope="project"), "scope project but the file sits in a global lessons folder"),
            (dict(scope="team"), "scope must be project or global"),
            (dict(**{"review-by": "next week"}), "review-by must be YYYY-MM-DD"),
            (dict(exempt="maybe"), "exempt must be"),
            (dict(exempt="yes"), "exempt must be"),
            (dict(lesson=None), "missing field 'lesson'"),
            (dict(role=None), "missing field 'role'"),
        ]
        for over, want in cases:
            self.lesson(self.gdir(), "2026-03-01-a-lesson", **over)
            self.ok("lessons", "index")
            out = self.check(1)
            self.assertIn(want, out, (over, out))
            self.assertIn("global/2026-03-01-a-lesson.md:", out)

    def test_scope_placement_in_a_repo_folder(self):
        self.lesson(self.rdir(), "2026-03-01-a-lesson", scope="global")
        self.ok("lessons", "index")
        self.assertIn("myapp/2026-03-01-a-lesson.md: scope global but the file sits in a project lessons folder", self.check(1))

    def test_bad_names_and_titles(self):
        self.lesson(self.gdir(), "no-date-here")
        self.ok("lessons", "index")
        self.assertIn("file name must be", self.check(1))
        os.unlink(os.path.join(self.gdir(), "no-date-here.md"))
        self.lesson(self.gdir(), "2026-03-01-" + "a" * 61)
        self.ok("lessons", "index")
        self.assertIn("file name must be", self.check(1))
        os.unlink(os.path.join(self.gdir(), "2026-03-01-" + "a" * 61 + ".md"))
        self.write(os.path.join(self.gdir(), "2026-03-01-no-title.md"), "- status: open\n- role: planner\n")
        self.ok("lessons", "index")
        out = self.check(1)
        self.assertIn("no `# title` line", out)

    def test_duplicate_field(self):
        self.write(os.path.join(self.gdir(), "2026-03-01-dup.md"),
                   "# t\n- status: open\n- status: open\n- role: planner\n- scope: global\n- summary: s\n- quote: none (observed: x)\n"
                   "- review-by: 2027-01-01\n- exempt: no\n- lesson: l\n")
        self.ok("lessons", "index")
        self.assertIn("field 'status' twice", self.check(1))

    def test_other_fields_and_continuation_lines_are_kept(self):
        self.write(os.path.join(self.gdir(), "2026-03-01-extra.md"),
                   "# t\n- status: open\n- role: planner\n- scope: global\n- summary: s\n- quote: none (observed: x)\n"
                   "- review-by: 2027-01-01\n- exempt: no\n- mood: calm\n- lesson: first part\n  second part\n")
        l = ls.parse_lesson("x", self.text(self.gdir(), "2026-03-01-extra.md"))
        self.assertEqual(l.get("mood"), "calm")
        self.assertEqual(l.get("lesson"), "first part\nsecond part")
        self.assertEqual([k for k, _ in l.fields][-2:], ["mood", "lesson"])
        self.ok("lessons", "index")
        self.check()

    def test_archive_files_are_validated_and_not_indexed(self):
        self.clean_global()
        self.lesson(os.path.join(self.gdir(), "archive"), "2026-02-01-old", status="archived")
        self.ok("lessons", "index")
        self.assertNotIn("2026-02-01", self.text(self.root, "LESSONS.md").split("Promoted and archived")[0])
        self.check()
        self.lesson(os.path.join(self.gdir(), "archive"), "2026-02-01-old", status="open")
        self.assertIn("status open but the file is in archive/", self.check(1))

    def test_check_takes_a_root(self):
        other = os.path.join(self.tmp, "elsewhere")
        self.write(os.path.join(other, "lessons", "2026-03-01-x.md"), "# t\n- status: open\n")
        rc, out, _ = self.run_orch("lessons", "check", "--root", other)
        self.assertEqual(rc, 1)
        self.assertIn("missing field", out)
        self.check()      # the real root is unaffected

    def test_check_is_read_only(self):
        self.clean_global()
        before = core.tree_hash(self.root)
        self.check()
        self.assertEqual(core.tree_hash(self.root), before)


