class LessonBase(core.Base):
    def setUp(self):
        core.Base.setUp(self)
        os.makedirs(os.path.join(self.root, "myapp"))

    def add(self, *extra, scope="global", repo=None, **kw):
        argv = list(ADD) + ["--scope", scope] + (["--repo", repo] if repo else []) + list(extra)
        return self.ok(*argv, **kw)

    def gdir(self):
        return os.path.join(self.root, "lessons")

    def rdir(self):
        return os.path.join(self.root, "myapp", "lessons")

    def text(self, *parts):
        return self.read(*parts).decode("utf-8")

    def write(self, path, text):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)

    def check(self, code=0):
        rc, out, err = self.run_orch("lessons", "check")
        self.assertEqual(rc, code, out + err)
        return out


