#!/usr/bin/env bash
# orch-index.sh — regenerate ~/.claude/orchestrations/ACTIVE.md: every non-finished task, one row each.
# Usage: orch-index.sh [--stdout]     (ORCH_DIR overrides the root). Local files only; never edits task files.
# Concurrency-safe: mkdir lock + rerun flag. A run that finds the lock held sets the flag and exits; the
# holder then regenerates again, so the last state change always lands. Output is replaced atomically (mv).
set -euo pipefail
root="${ORCH_DIR:-$HOME/.claude/orchestrations}"
out="$root/ACTIVE.md"
[ "${1:-}" = "--stdout" ] && out=/dev/stdout
[ "${1:-}" = "-h" ] && { sed -n 2,3p "$0"; exit 0; }

generate() {
  body=$(python3 -I - "$root" <<'PY'
import sys, os, re, glob, time, datetime
root = sys.argv[1]
ENUM = {"planning","awaiting_approval","implementing","reviewing","awaiting_merge","paused_usage_limit","done","abandoned"}
TERMINAL = {"done","abandoned","merged"}
rows = []
for sf in sorted(glob.glob(os.path.join(root, "*", "*", "status.md"))):
    d = os.path.dirname(sf); repo = os.path.basename(os.path.dirname(d)); slug = os.path.basename(d)
    txt = open(sf, errors="replace").read()
    def field(k):
        m = re.search(r"^- %s:\s*(.*)$" % k, txt, re.M)
        return m.group(1).strip() if m else ""
    raw = field("task_state")
    first = re.sub(r"[^a-z_]", "", (raw.split() or [""])[0].lower()) if raw and "|" not in raw else ""
    if first in ENUM or first in TERMINAL: state = first
    elif first.startswith(("done","merged")): state = "done"
    elif first: state = first
    elif os.path.exists(os.path.join(d, "retro.md")): state = "done"
    else:
        m = re.search(r"^\|\s*orchestrator\s*\|\s*(\w+)", txt, re.M)  # legacy files without task_state
        state = "done" if m and m.group(1) == "done" else "unknown"
    if state == "unknown" and re.match(r"removed", field("worktree")): state = "done"  # legacy: merged + cleaned up
    if state in TERMINAL: continue
    log = os.path.join(d, "log.md")
    last = ""
    if os.path.exists(log):
        ls = [l.strip() for l in open(log, errors="replace") if l.strip().startswith("-")]
        last = ls[-1].lstrip("- ").replace("|", "/")[:140] if ls else ""
    mt = max(os.path.getmtime(p) for p in (sf, log) if os.path.exists(p))
    age = (time.time() - mt) / 86400
    wt = re.sub(r"\s*\(.*$", "", field("worktree")) or "-"
    rows.append((repo, slug, state, wt, datetime.datetime.fromtimestamp(mt).strftime("%Y-%m-%d %H:%M"), "STALE>7d " if age > 7 else "", last, d))
def table(rs):
    print("| repo | task | state | worktree | updated | last log line | task dir |")
    print("|---|---|---|---|---|---|---|")
    for r in rs:
        print("| %s | %s | %s | %s | %s | %s%s | %s |" % (r[0], r[1], r[2], r[3], r[4], r[5], r[6], r[7]))
    if not rs: print("| _none_ | | | | | | |")
act = [r for r in rows if not (r[2] == "unknown" and r[5])]
tri = [r for r in rows if r[2] == "unknown" and r[5]]
print("## Active"); print(); table(act)
if tri:
    print(); print("## Needs triage (no usable task_state and untouched >7d — usually finished legacy tasks; verify via log.md, then set `task_state: done`)"); print(); table(tri)
PY
  )
    tmp=$(mktemp "${TMPDIR:-/tmp}/orch-index.XXXXXX")
  {
    echo "# Active orchestration tasks"
    echo
    echo "<!-- GENERATED by ~/.claude/bin/orch-index.sh — do not edit; re-run it. -->"
    echo "Generated $(date -u +%Y-%m-%dT%H:%MZ). To resume a task: read its \`status.md\` (state, worktree, role rows), then the tail of \`log.md\`, then \`plan.md\` Summary."
    echo "State \`unknown\` = status.md has no usable \`task_state:\` — check the task's \`log.md\`. Finished tasks are omitted."
    echo
    echo "$body"
  } > "$tmp"
  if [ "$out" = /dev/stdout ]; then cat "$tmp"; rm -f "$tmp"; else mv "$tmp" "$out"; fi
}

if [ "$out" = /dev/stdout ]; then generate; exit 0; fi

mkdir -p "$root"
lock="$root/.ACTIVE.lock"; flag="$root/.ACTIVE.rerun"
while :; do
  if ! mkdir "$lock" 2>/dev/null; then
    pid=$(cat "$lock/pid" 2>/dev/null || true)
    if [ -n "$pid" ] && ! kill -0 "$pid" 2>/dev/null; then rm -rf "$lock"; continue; fi  # holder died
    : > "$flag"; exit 0                                                                    # holder will rerun
  fi
  echo $$ > "$lock/pid"
  trap 'rm -rf "$lock"' EXIT
  while :; do rm -f "$flag"; generate; [ -e "$flag" ] || break; done
  rm -rf "$lock"; trap - EXIT
  [ -e "$flag" ] || break
done
